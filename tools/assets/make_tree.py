#!/usr/bin/env python3
"""Procedural bare/dead tree silhouettes (RGBA PNG, black on transparent) for outside windows.

Output: public/assets/textures/tree_silhouette_{1,2}.png (1024x1024, trunk base at bottom centre).
"""
import math, json, pathlib, random
from PIL import Image, ImageDraw, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "public/assets/textures"
SS = 2
W = H = 1024 * SS


def branch(d, x, y, ang, length, width, depth, rnd):
    if depth == 0 or length < 6 * SS or width < 0.6 * SS:
        return
    # draw a slightly crooked segment as several sub-segments
    segs = 4
    px, py, a = x, y, ang
    for i in range(segs):
        a += rnd.uniform(-0.18, 0.18)
        nl = length / segs
        nx, ny = px + math.cos(a) * nl, py - math.sin(a) * nl
        w = width * (1 - 0.35 * (i + 1) / segs)
        d.line([(px, py), (nx, ny)], fill=(0, 0, 0, 255), width=max(1, int(w)))
        r = w / 2
        d.ellipse([nx - r, ny - r, nx + r, ny + r], fill=(0, 0, 0, 255))
        px, py = nx, ny
    n = rnd.choice([2, 2, 3]) if depth > 2 else rnd.choice([1, 2, 2, 3])
    for _ in range(n):
        spread = rnd.uniform(0.25, 0.75) * rnd.choice([-1, 1])
        # gnarled: occasionally a branch droops
        droop = -0.5 if rnd.random() < 0.12 else 0
        branch(d, px, py, a + spread + droop, length * rnd.uniform(0.62, 0.8), width * 0.62, depth - 1, rnd)


def make(seed, path):
    rnd = random.Random(seed)
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    base_x = W / 2 + rnd.uniform(-60, 60) * SS
    # roots/flare
    for k in range(5):
        a = math.pi + k * math.pi / 4 + rnd.uniform(-0.1, 0.1)
        d.line([(base_x, H - 4), (base_x + math.cos(a) * 90 * SS, H - 4 - abs(math.sin(a)) * 12 * SS)], fill=(0, 0, 0, 255), width=18 * SS)
    branch(d, base_x, H, math.pi / 2 + rnd.uniform(-0.08, 0.08), 330 * SS, 62 * SS, 8, rnd)
    img = img.filter(ImageFilter.GaussianBlur(0.8 * SS)).resize((1024, 1024), Image.LANCZOS)
    img.save(path, optimize=True)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for i, seed in enumerate((13, 666), 1):
        make(seed, OUT / f"tree_silhouette_{i}.png")
    mpath = OUT / "manifest.json"
    m = json.loads(mpath.read_text())
    m["decals"] = {
        "tree_silhouette_1": {"file": "tree_silhouette_1.png", "note": "RGBA black dead-tree silhouette, trunk base at bottom centre; for window backdrops (lit by lightning)", "license": "CC0 (generated by tools/assets/make_tree.py)"},
        "tree_silhouette_2": {"file": "tree_silhouette_2.png", "note": "variant", "license": "CC0 (generated by tools/assets/make_tree.py)"},
    }
    mpath.write_text(json.dumps(m, indent=2))
    print("trees written")
